#!/usr/bin/env python3
"""Stage 4: render the one-page human summary (Markdown) and the ranked next-steps list from the ledger.  Every number
in the summary is copied from a ledger cell or a QC count; a checker refuses to write the file if any number in the prose
is not found in the ledger/QC number set.  No LLM call is made here; an LLM may only rewrite the produced text, and the
rewrite must pass the same check_numbers() before use.  Standard library only.

Usage: python -X utf8 summarize.py --ledger ledger.csv --qc qc.json --runs runs.csv --out summary.md --next next_steps.md
          [--tokens-per-hour 1000000] [--label MOCK]
"""
import argparse
import csv
import json
import re
import sys
from collections import defaultdict

NUM = re.compile(r"(?<![A-Za-z\d.\-_])-?\d+(?:\.\d+)?(?![A-Za-z\d_])")


def allowed_numbers(ledger, qc, extra):
    """Every numeric token that may appear in the prose: ledger cells (as written and rounded to 3/2/1/0 decimals), QC counts."""
    allowed = set(extra)
    cells = [v for r in ledger for v in r.values()] + [json.dumps(qc["checks"]), json.dumps(qc["refusal_by_model_arm"])]
    for c in cells:
        for tok in NUM.findall(str(c)):
            allowed.add(tok)
            try:
                x = float(tok)
                for nd in (3, 2, 1, 0):
                    allowed.add(("%." + str(nd) + "f") % x)
                allowed.add(str(int(round(x))))
            except ValueError:
                pass
    return allowed


def check_numbers(text, allowed):
    """Returns the numeric tokens of the text that are not in the allowed set (empty = passes)."""
    return sorted(set(t for t in NUM.findall(text) if t not in allowed and t.lstrip("-") not in allowed))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    for k in ("ledger", "qc", "runs", "out", "next"):
        ap.add_argument("--" + k, required=True)
    ap.add_argument("--tokens-per-hour", type=float, default=1e6, help="token volume treated as one hour of cost in the ROI")
    ap.add_argument("--label", default="MOCK")
    ap.add_argument("--verify-rewrite", help="a rewritten summary (for example LLM-edited prose) to verify instead of writing: every "
                    "protected line (verdict table rows, exploratory findings, controls) must appear verbatim and every number must "
                    "be in the ledger/QC set; exit 1 otherwise (review finding 5: tokens alone do not pin a number to its claim)")
    a = ap.parse_args()
    ledger = list(csv.DictReader(open(a.ledger, encoding="utf-8", newline="")))
    qc = json.load(open(a.qc, encoding="utf-8"))
    runs = list(csv.DictReader(open(a.runs, encoding="utf-8", newline="")))
    gate = ledger[0]["gate"] if ledger else "NO LEDGER"
    models = sorted(set(r["models"] for r in ledger))
    tok_in, tok_out = sum(int(r["tokens_in"]) for r in runs), sum(int(r["tokens_out"]) for r in runs)
    tok_per_run = defaultdict(list)
    for r in runs:
        tok_per_run[(r["arm"], r["model"])].append(int(r["tokens_in"]) + int(r["tokens_out"]))
    mean_tok = int(round(sum(sum(v) for v in tok_per_run.values()) / max(1, len(runs))))
    n_shards, n_runs = len(qc["shards"]), qc["checks"]["runs_kept"]
    paraphrases = len(set(r["paraphrase"] for r in runs))
    seeds = len(set(r["seed"] for r in runs))
    extra = {str(x) for x in (tok_in, tok_out, mean_tok, n_shards, n_runs, paraphrases, seeds, len(models), qc["checks"]["cache_conflicts"], qc["checks"]["runs_dropped_duplicates"])}
    extra |= {"2026", "10", "23", "4000", "0.05", "0.10", "0.1", "0.5", "30", "95"}    # date, B, alpha, BH level, 95% level, thresholds from PREDICTIONS.md

    pre = [r for r in ledger if re.match(r"^(P1-A|P3|P4|P5|P6a|P6b|P6c|P6d|P7)@", r["finding_id"])]   # the fixed family of tools/analysis.py
    exp = [r for r in ledger if re.match(r"^X[0-9]+@", r["finding_id"])]
    ctrl = [r for r in ledger if r["section"] == "controls"]
    ref = [r for r in ledger if r["section"] == "refusals"]
    L = ["# One-page summary (%s DATA; gate %s)" % (a.label, gate), "", "Generated by summarize.py from ledger.csv on 2026-10-23. Every number below is a ledger or QC value; nothing is typed by hand.", ""]
    if not gate.startswith("PASS"):
        L += ["**The sanity gate failed (%s). No verdict below may be read as a result until it passes.**" % gate, ""]
    L += ["## Headline verdicts (pre-declared family, Holm over the fixed family, one-sided, B = 4000)", "", "| prediction | model | outcome | point | lower | upper | band edge | n A/B | caveat |", "|---|---|---|---|---|---|---|---|---|"]
    for r in pre:
        outcome = re.search(r"outcome=(\w+)", r["family_status"]).group(1)
        L.append("| %s | %s | %s (%s) | %s | %s | %s | %s | %s | %s |" % (r["finding_id"].split("@")[0], r["models"], outcome, r["confidence"], r["point"] or "n/a", r["lower"] or "n/a",
                                                                       r["upper"] or "n/a", r["band_edge"] or "none", r["n_per_arm"], r["caveats"].split(";")[0][:60]))
    L += ["", "## Exploratory findings (BH over the exploratory family at 0.10; top by interestingness; B = significant and robust, C = suggestive)", ""]
    top = sorted((r for r in exp if r["confidence"] in ("B", "C") and r["point"]), key=lambda r: -float(r["score"] or 0))[:5]
    if not top:
        L.append("No exploratory contrast reached confidence B or C.")
    for r in top:
        L.append("- **%s** (%s, score %s, model %s): %s. Oriented point %s, one-sided 95%% lower bound %s; %s; spread %s; %s. Caveats: %s" % (
            r["finding_id"].split("@")[0], r["confidence"], r["score"], r["models"], r["claim"], r["point"], r["lower"], r["family_status"], r["paraphrase_spread"], r["refusal_bound"], r["caveats"]))
    L += ["", "## Controls (P2 harness check; P1-A' sanity control)", ""]
    for r in ctrl:
        L.append("- %s: %s = %s [%s, %s] n %s; %s" % (r["models"], r["claim"], r["point"] or "n/a", r["lower"] or "n/a", r["upper"] or "n/a", r["n_per_arm"] or "n/a", r["family_status"]))
    L += ["", "## Refusal picture", ""]
    hi = [r for r in ref if r["point"] and float(r["point"]) > 0]
    L.append("Arms with any refusal: " + ("; ".join("%s@%s %s (n %s)" % (r["contrast"], r["models"], r["point"], r["n_per_arm"]) for r in hi) if hi else "none") + ".")
    L += ["", "## Cost and provenance", "", "%d runs kept from %d shards; %d models; %d paraphrases x %d seeds in the data; tokens in %d, out %d (mean %d per run); cache conflicts %d; duplicate run lines dropped %d; git commits %s; analysis.py sha12 %s; model snapshots %s." % (
        n_runs, n_shards, len(models), paraphrases, seeds, tok_in, tok_out, mean_tok, qc["checks"]["cache_conflicts"], qc["checks"]["runs_dropped_duplicates"],
        " ".join(c[:12] for c in qc["checks"]["git_commits"]), runs[0]["analysis_sha12"] if runs else "n/a", " ".join(sorted(qc["checks"]["model_snapshots"]))), ""]
    L += ["## Limitations", "", "Statements are about the models tested, not about LLMs in general. Refusers are excluded from the primary estimates (post-treatment selection; bounds shown where arm refusal rates differ by more than 0.10). Exploratory findings are screened, not pre-registered; confidence B requires replication before it carries claim weight. Pre-declared INCONCLUSIVE outcomes count neither way."]
    if a.label == "MOCK":
        L += ["", "**MOCK: the 'models' are scripted MockLlmServer behaviours; no number here is a result about any LLM.**"]
    text = "\n".join(L) + "\n"
    allowed = allowed_numbers(ledger, qc, extra)
    bad = check_numbers(text, allowed)
    if bad:
        print("NUMBER CHECK FAILED: tokens not in the ledger/QC set:", bad)
        return 1
    if a.verify_rewrite:
        # protected lines: the verdict table rows, the exploratory findings, the controls and the refusal line are template
        # output and must survive any rewrite byte for byte; only the surrounding prose (caveats, limitations) may change
        candidate = open(a.verify_rewrite, encoding="utf-8").read()
        protected = [l for l in L if (l.startswith("| ") and not l.startswith("| prediction")) or l.startswith("- ") or l.startswith("Arms with any refusal")]
        missing = [l for l in protected if l not in candidate]
        bad2 = check_numbers(candidate, allowed)
        if missing or bad2:
            print("REWRITE CHECK FAILED: %d protected line(s) altered or missing; numbers not in the ledger/QC set: %s" % (len(missing), bad2))
            for l in missing[:5]:
                print("  missing:", l[:120])
            return 1
        print("rewrite check passed: %d protected lines intact, all numbers in the ledger/QC set ->" % len(protected), a.verify_rewrite)
        return 0
    open(a.out, "w", encoding="utf-8").write(text)
    print("summary written (number check passed) ->", a.out)

    # ---------------------------------------------------------------- next steps with ROI = gain / (hours + tokens/tokens_per_hour)
    steps = []

    def add(action, gain, hours, tokens, why):
        cost = hours + tokens / a.tokens_per_hour
        steps.append({"roi": gain / cost if cost > 0 else float("inf"), "gain": gain, "hours": hours, "tokens": int(tokens), "action": action, "why": why})

    if not gate.startswith("PASS"):
        add("fix the sanity gate: " + gate, 10, 1.0, 0, "no result can be read before the gate passes")
    for k in qc["checks"].get("cross_arm_hash_overlap", {}):
        add("drop or re-render the arm pair %s (identical requests)" % k, 5, 0.5, 0, "the arms are the same experiment at the request level")
    for r in pre:
        cid, model = r["finding_id"].split("@")
        outcome = re.search(r"outcome=(\w+)", r["family_status"]).group(1)
        nA, nB = (int(x) for x in r["n_per_arm"].split("/"))
        tpr = mean_tok
        if outcome == "INCONCLUSIVE" and "not decisive" in r["caveats"] and r["point"] and float(r["point"]) > 0:
            extra_runs = 2 * 2 * paraphrases * 4
            add("add 4 seeds per paraphrase to both arms of %s on %s" % (cid, model), 3, 0.5, extra_runs * tpr, "point %s in the predicted direction, interval not decisive" % r["point"])
        elif outcome == "INCONCLUSIVE" and "fewer than" in r["caveats"] and (nA or nB):
            need = max(0, 30 - nA) + max(0, 30 - nB)
            add("complete the cells of %s on %s to 30 runs (%d runs missing)" % (cid, model, need), 3, 0.5, need * tpr, "n per arm %s" % r["n_per_arm"])
        elif outcome == "INCONCLUSIVE" and (nA == 0 or nB == 0) and "not built" not in r["caveats"]:
            add("run the missing cell(s) of %s on %s (%d runs per arm)" % (cid, model, 2 * paraphrases * 3), 3, 2.0, 2 * paraphrases * 3 * tpr * 2, "no data in at least one arm")
    for r in exp:
        cid, model = r["finding_id"].split("@")
        if r["confidence"] == "B":
            add("confirm %s on %s with fresh seeds (replication on held-out seeds, pre-registered)" % (cid, model), 2, 0.5, 2 * paraphrases * 3 * mean_tok, "BH-significant and robust: " + r["claim"][:60])
        elif r["confidence"] == "C":
            add("add seeds to %s on %s" % (cid, model), 1, 0.5, 2 * paraphrases * 3 * mean_tok, "suggestive: " + r["claim"][:60])
    tested = defaultdict(set)
    for r in pre + exp:
        if r["point"]:
            tested[r["finding_id"].split("@")[0]].add(r["models"])
    single = [cid for cid, ms in tested.items() if len(ms) == 1]
    if single and len(models) > 1:
        add("run the second model on %s" % ", ".join(sorted(single)), 2, 1.0, len(single) * 2 * paraphrases * 3 * mean_tok, "replication across models is part of robustness")
    for r in ref:
        if r["point"] and float(r["point"]) > 0.30:
            add("re-prompt or drop arm %s on %s (refusal %s); report the refusal bound beside it" % (r["contrast"], r["models"], r["point"]), 1, 0.5, 0, "refusal above 0.30 makes the excluded-refuser estimate a selected sample")
    steps.sort(key=lambda s: -s["roi"])
    N = ["# Ranked next steps (%s; ROI = gain / (hours + tokens / %d))" % (a.label, int(a.tokens_per_hour)), "", "| rank | ROI | gain | hours | tokens | action | why |", "|---|---|---|---|---|---|---|"]
    for i, s in enumerate(steps, 1):
        N.append("| %d | %s | %d | %.1f | %d | %s | %s |" % (i, "inf" if s["roi"] == float("inf") else "%.2f" % s["roi"], s["gain"], s["hours"], s["tokens"], s["action"], s["why"]))
    open(a.next, "w", encoding="utf-8").write("\n".join(N) + "\n")
    print("next steps: %d -> %s" % (len(steps), a.next))
    return 0


if __name__ == "__main__":
    sys.exit(main())
